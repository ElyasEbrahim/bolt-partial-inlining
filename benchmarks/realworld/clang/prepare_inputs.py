#!/usr/bin/env python3
"""Timing inputs of the clang workload, prepared with the clang just built.

  prepare_inputs.py <llvm-src> <clang-build-dir> <out-dir> <final-dir>

Preprocesses LLVM translation units that the training (a Release build of
LLVMSupport, see train.sh) does not compile, with the flags of the LLVM
Release build from compile_commands.json:
  * llvm/lib/IR/Verifier.cpp and llvm/lib/Transforms/Scalar/GVN.cpp (timed),
  * llvm/lib/Transforms/Utils/LowerSwitch.cpp (instruction counts).
The build's precompiled header was made by the build compiler; its header is
included as a normal header instead. Writes to <out-dir>, with paths that
refer to <final-dir>, where the files are installed in the evaluation image:
  inputs/<name>.ii
  compile.sh        the timed workload: compiles the SQLite amalgamation
                    (inputs/sqlite3.i, preprocessed at run time by
                    scripts/prepare_realworld.sh) with -O2 and the two LLVM
                    files with their Release flags (-O3), with the clang given
                    as $1, and prints the SHA-256 of the object files
  icount-cmd.json   the clang command line for the instruction counts
"""
import json
import os
import shlex
import subprocess
import sys

SRC, B, OUT, FINAL = sys.argv[1:5]
TIMED = ["llvm/lib/IR/Verifier.cpp", "llvm/lib/Transforms/Scalar/GVN.cpp"]
SMALL = "llvm/lib/Transforms/Utils/LowerSwitch.cpp"
CLANG = os.path.join(B, "bin", "clang")

major = subprocess.run([CLANG, "-dumpversion"], check=True, capture_output=True,
                       text=True).stdout.strip().split(".")[0]
resource = f"-resource-dir={FINAL}/lib/clang/{major}"
with open(os.path.join(B, "compile_commands.json")) as f:
    cmds = {c["file"]: c for c in json.load(f)}
os.makedirs(os.path.join(OUT, "inputs"), exist_ok=True)


def split_flags(cmd):
    """(preprocessing flags, compilation flags) of a compile command, without
    the compiler, the output, the input and the dependency-file options."""
    args = shlex.split(cmd)[1:]
    pre, comp, i = [], [], 0
    while i < len(args):
        a = args[i]
        if a in ("-o", "-MT", "-MF"):
            i += 2
            continue
        if a in ("-c", "-MD", "-Winvalid-pch"):
            i += 1
            continue
        if a == "-Xclang" and i + 3 < len(args) and args[i + 1] == "-include-pch":
            i += 4
            continue
        if a == "-Xclang" and i + 3 < len(args) and args[i + 1] == "-include":
            pre += ["-include", args[i + 3]]
            i += 4
            continue
        if a == "-Xclang" and i + 1 < len(args) and args[i + 1] == "-fno-pch-timestamp":
            i += 2
            continue
        if os.path.isabs(a) and a.endswith((".cpp", ".c")):
            i += 1
            continue
        if a.startswith(("-I", "-D", "-isystem")):
            pre.append(a)
            if a in ("-I", "-D", "-isystem"):
                pre.append(args[i + 1])
                i += 1
            i += 1
            continue
        pre.append(a)
        comp.append(a)
        i += 1
    return pre, comp


def prepare(src):
    """Preprocess one LLVM file; return its name and compilation flags."""
    name = os.path.splitext(os.path.basename(src))[0]
    pre, comp = split_flags(cmds[os.path.join(SRC, src)]["command"])
    subprocess.run([CLANG] + pre + ["-E", os.path.join(SRC, src), "-o",
                                    os.path.join(OUT, "inputs", name + ".ii")],
                   check=True, cwd=B)
    return name, comp


lines = ["#!/bin/sh",
         "# Generated by benchmarks/realworld/clang/prepare_inputs.py: the timed",
         "# clang workload. Usage: compile.sh <clang>",
         "set -e",
         'C=$1; O=${OBJ_DIR:-/tmp/clang-obj}; mkdir -p "$O"',
         # -w: the preprocessed amalgamation triggers warnings that macros
         # suppress in the original source; diagnostics are not measured.
         f'"$C" {resource} -O2 -w -c {FINAL}/inputs/sqlite3.i -o "$O/sqlite3.o"']
names = []
for src in TIMED:
    name, comp = prepare(src)
    names.append(name)
    lines.append(f'"$C" {resource} {shlex.join(comp)} -c {FINAL}/inputs/{name}.ii '
                 f'-o "$O/{name}.o"')
lines.append('cd "$O" && sha256sum sqlite3.o ' + " ".join(n + ".o" for n in names))
with open(os.path.join(OUT, "compile.sh"), "w") as f:
    f.write("\n".join(lines) + "\n")
os.chmod(os.path.join(OUT, "compile.sh"), 0o755)

# valgrind does not follow child processes: the instruction count runs clang
# itself (with -c, the driver runs the compiler in-process).
name, comp = prepare(SMALL)
with open(os.path.join(OUT, "icount-cmd.json"), "w") as f:
    json.dump(["@BIN@", resource] + comp
              + ["-c", f"{FINAL}/inputs/{name}.ii", "-o", f"/tmp/{name}.o"], f)
